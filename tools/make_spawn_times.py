"""Regenerates src/WhereEQ/Data/SpawnTimes/spawntimes.txt from EqTool's EQToolShared/Zones.cs (MIT).

Usage: python tools/make_spawn_times.py <path to Zones.cs> <EqTool commit>

Output lines (tab separated):
    zone    *          h:mm:ss    default respawn for the zone (0:00:00 = none / unknown)
    zone    =Name      h:mm:ss    exact NPC name
    zone    ~text      h:mm:ss    NPC name contains text
"""
import re
import sys

src, commit = sys.argv[1], sys.argv[2]
text = open(src, encoding="utf-8-sig").read()


TIME = r"(new TimeSpan\([^)]*\)|TimeSpan\.From(?:Hours|Minutes|Seconds)\([\d.]+\))"


def span(expr: str) -> str:
    f = re.match(r"TimeSpan\.From(Hours|Minutes|Seconds)\(([\d.]+)\)", expr)
    if f:
        secs = int(float(f.group(2)) * {"Hours": 3600, "Minutes": 60, "Seconds": 1}[f.group(1)])
        return f"{secs // 3600}:{secs // 60 % 60:02}:{secs % 60:02}"
    args = expr[expr.index("(") + 1 : expr.rindex(")")]
    n = [int(x) for x in args.replace(" ", "").split(",") if x]
    if len(n) == 1:
        secs = n[0] // 10_000_000  # ticks
    elif len(n) == 3:
        secs = n[0] * 3600 + n[1] * 60 + n[2]
    elif len(n) == 4:
        secs = n[0] * 86400 + n[1] * 3600 + n[2] * 60 + n[3]
    else:
        raise ValueError(args)
    return f"{secs // 3600}:{secs // 60 % 60:02}:{secs % 60:02}"


blocks = re.split(r'ZoneInfoMap\.Add\("', text)[1:]
out = [
    f"# P1999 respawn times, generated by tools/make_spawn_times.py from EqTool (MIT) commit {commit[:7]}.",
    "# See NOTICE.md. Columns: zone short name, * (zone default) / =exact NPC / ~NPC name contains, h:mm:ss.",
]
for b in blocks:
    zone = b[: b.index('"')].lower()
    # Zone default: the RespawnTime that is not inside an NpcSpawnTime { ... }.
    npc_re = re.compile(r'new NpcSpawnTime\s*\{\s*Name\s*=\s*"([^"]+)"\s*,\s*RespawnTime\s*=\s*' + TIME + r'\s*,?\s*\}')
    stripped = npc_re.sub("", b)
    m = re.search(r"RespawnTime\s*=\s*" + TIME, stripped)
    if m:
        out.append(f"{zone}\t*\t{span(m.group(1))}")
    for nm in npc_re.finditer(b):
        # Which list is this entry in? The nearest list name before it.
        before = b[: nm.start()]
        kind = "~" if before.rfind("NpcContainsSpawnTimes") > before.rfind("NpcSpawnTimes =") else "="
        out.append(f"{zone}\t{kind}{nm.group(1)}\t{span(nm.group(2))}")
    # Freeport guards are built in code: listofGuards.Select(guard => new NpcSpawnTime { ..., RespawnTime = X })
    if "NpcSpawnTimes = guardspawns" in b:
        g = re.search(r"listofGuards = new List<string>\(\)\s*\{(.*?)\};", text, re.S)
        t = re.search(r"guardspawns = .*?RespawnTime = " + TIME, text, re.S)
        for name in re.findall(r'"([^"]+)"', g.group(1)):
            out.append(f"{zone}\t={name}\t{span(t.group(1))}")

sys.stdout.reconfigure(encoding="utf-8", newline="\r\n")
print("\n".join(out))
